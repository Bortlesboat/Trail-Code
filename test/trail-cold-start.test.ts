/**
 * The first-run read of past Claude sessions: which transcripts are the repo's,
 * what counts as the person's own words, and that a finding survives only
 * when the quotes it cites really are in two or more sessions.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { digest, ownWords, readSession, scrub, sessionFiles, verify, type PastSession } from "../src/notes/cold-start.js";
import { savedLine } from "../src/notes/notes.js";
import { claudeProjectDir } from "../src/notes/session-cost.js";

function transcript(entries: object[]): string {
  return entries.map((e) => JSON.stringify(e)).join("\n") + "\n";
}

const user = (content: unknown, extra: object = {}) => ({ type: "user", cwd: "/r", timestamp: "2026-10-01T10:00:00Z", message: { role: "user", content }, ...extra });
const said = (text: string) => ({ type: "assistant", message: { content: [{ type: "text", text }] } });

test("only the person's own words count: wrappers, hand-backs and pasted text are dropped", () => {
  assert.equal(ownWords("<command-name>/plan-my-work</command-name>"), null);
  assert.equal(ownWords("Caveat: the messages below were generated by the user"), null);
  assert.equal(ownWords("Another Claude session sent a message: done"), null);
  assert.equal(ownWords("<system-reminder>x</system-reminder>"), null);
  assert.equal(ownWords('use a worktree <pasted_content id="1">lots</pasted_content id="1">'), "use a worktree [pasted text]");
  assert.equal(ownWords("no, open the PR against dev"), "no, open the PR against dev");
});

test("a session keeps the person's messages with the end of what Claude said before each", () => {
  const dir = mkdtempSync(join(tmpdir(), "cold-read-"));
  const f = join(dir, "s1.jsonl");
  writeFileSync(
    f,
    transcript([
      user("fix the login bug"),
      said("I pushed the fix to main."),
      user("no, never push to main, open a PR against dev"),
      user([{ type: "tool_result", content: "ok" }]),
      user("<task-notification>done</task-notification>", { origin: { kind: "task-notification" } }),
      user("hand-back", { isSidechain: true }),
    ]),
  );
  const s = readSession(f)!;
  assert.equal(s.id, "s1");
  assert.deepEqual(s.prompts.map((p) => p.text), ["fix the login bug", "no, never push to main, open a PR against dev"]);
  assert.equal(s.prompts[1]!.before, "I pushed the fix to main.");
});

test("a headless run is skipped whole: its prompt was written once and replayed", () => {
  const dir = mkdtempSync(join(tmpdir(), "cold-sdk-"));
  const f = join(dir, "s.jsonl");
  writeFileSync(f, transcript([user("summarise the repo", { entrypoint: "sdk-cli" })]));
  assert.equal(readSession(f), null);
});

test("a repo's sessions are its own and its worktrees', not a sibling's with the same prefix", () => {
  const home = mkdtempSync(join(tmpdir(), "cold-home-"));
  const repo = "/work/assign";
  const write = (folderOf: string, cwd: string, name: string) => {
    const d = claudeProjectDir(folderOf, home);
    mkdirSync(d, { recursive: true });
    writeFileSync(join(d, `${name}.jsonl`), transcript([user("hi", { cwd })]));
  };
  write(repo, repo, "main");
  write(`${repo}/.claude/worktrees/x`, `${repo}/.claude/worktrees/x`, "worktree");
  write("/work/assign-old", "/work/assign-old", "sibling");
  const names = sessionFiles([repo], home).map((p) => p.split("/").pop()).sort();
  assert.deepEqual(names, ["main.jsonl", "worktree.jsonl"]);
});

function session(id: string, at: string, ...texts: string[]): PastSession {
  return { id, at, prompts: texts.map((text) => ({ text })) };
}

test("a finding is kept only when its quotes are in two sessions, and they're counted by trail", () => {
  const sessions = [
    session("aaaaaaaa-1", "2026-10-09T00:00:00Z", "no, open the PR against the dev branch please"),
    session("bbbbbbbb-2", "2026-10-01T00:00:00Z", "again: open the PR against the dev branch"),
    session("cccccccc-3", "2026-09-20T00:00:00Z", "something else entirely"),
  ];
  const { ids } = digest(sessions);
  const out = verify(
    [
      {
        title: "Open PRs against dev",
        for: "team",
        body: "## Decided\n- PRs go to dev.",
        evidence: [
          { session: "aaaaaaaa", quote: "open the PR against the dev branch" },
          // Filed under the wrong session: still counts for the one it's in.
          { session: "cccccccc", quote: "Open the PR against the DEV branch" },
        ],
      },
      { title: "Made up", for: "you", body: "## Decided\n- x", evidence: [{ session: "aaaaaaaa", quote: "never said anything like this" }, { session: "bbbbbbbb", quote: "nor this one either" }] },
      { title: "Only once", for: "you", body: "## Decided\n- y", evidence: [{ session: "cccccccc", quote: "something else entirely" }] },
    ],
    sessions,
    ids,
  );
  assert.equal(out.length, 1);
  assert.equal(out[0]!.title, "Open PRs against dev");
  assert.deepEqual(out[0]!.sessions, ["aaaaaaaa-1", "bbbbbbbb-2"]);
  assert.equal(out[0]!.last, "2026-10-09");
});

test("the digest is newest first and stops at its size", () => {
  const sessions = [session("new00000", "2026-10-09T00:00:00Z", "x".repeat(50)), session("old00000", "2026-09-01T00:00:00Z", "y".repeat(50))];
  const small = digest(sessions, 90);
  assert.ok(small.text.startsWith("=== session new00000"));
  assert.deepEqual([...small.ids.keys()], ["new00000"]);
});

test("anything like a credential or an email is scrubbed before a learning is written", () => {
  const out = scrub("use ghp_abcdefghijklmnopqrstuvwxyz1234 and password: hunter2 for anirudh@acme.test, key AKIAABCDEFGHIJKLMNOP");
  assert.ok(!out.includes("ghp_"));
  assert.ok(!out.includes("hunter2"));
  assert.ok(!out.includes("anirudh@acme.test"));
  assert.ok(!out.includes("AKIA"));
});

test("the closing line says who a learning is for, and what it took when trail knows", () => {
  assert.equal(savedLine({ scope: "personal" }), "📝 Saved just for you · stays on this machine, out of the repo");
  assert.equal(
    savedLine({ scope: "repo", cost: { minutes: 6, tokens: 41000 } }),
    "📝 Saved for your team · took 6 min and ~41k tokens to work out · commit it and your teammates' Claude skips that",
  );
  assert.equal(savedLine({ scope: "repo" }), "📝 Saved for your team · commit it and your teammates' Claude starts from it");
});
